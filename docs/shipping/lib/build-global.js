#!/usr/bin/env node
/* Build the plain <script>-tag version from the ES modules.
 *
 * No bundler, no package manager, no dependencies — node builtins only.
 * The modules are concatenated into one IIFE, so cross-module references just
 * work; `import` lines are dropped and `export` keywords stripped.
 *
 * THE LIBRARY NAME LIVES HERE AND NOWHERE ELSE. Rename `NAME` and the global
 * changes; the class name is `MushafPage` in core.mjs.
 *
 *   node build-global.js        ->  mushaf.global.js
 */
const fs = require('fs');
const path = require('path');

const NAME = 'Mushaf';                       // <- the single naming decision
const OUT = 'mushaf.global.js';

/* dependency order: core first, then everything that uses it */
const MODULES = ['core.mjs', 'layout.mjs', 'overlay.mjs', 'selection.mjs', 'memorize.mjs',
                 'a11y.mjs', 'view.mjs', 'raster.mjs', 'atlas.mjs', 'markers.mjs'];

const here = __dirname;
const exported = [];
const bodies = [];

for (const file of MODULES) {
  let src = fs.readFileSync(path.join(here, file), 'utf8');
  /* drop import lines — everything lands in one scope */
  src = src.replace(/^\s*import\s+[^;]*;\s*$/gm, '');
  /* collect and strip exports */
  src = src.replace(/^export\s+(async\s+)?(function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm,
    (m, a, kind, name) => { exported.push(name); return `${a || ''}${kind} ${name}`; });
  if (/^export\s/m.test(src)) {
    throw new Error(`${file}: an export form the build script does not handle:\n` +
      src.split('\n').filter(l => /^export\s/.test(l)).join('\n'));
  }
  bodies.push(`/* ===== ${file} ===== */\n${src.trim()}\n`);
}

const dupes = exported.filter((n, i) => exported.indexOf(n) !== i);
if (dupes.length) throw new Error('duplicate export names across modules: ' + dupes.join(', '));

/* everything lands in one scope, so top-level names must be unique across
 * modules too — not just the exported ones */
const tops = [];
for (const b of bodies)
  for (const m of b.matchAll(/^(?:async\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm))
    tops.push(m[1]);
const topDupes = [...new Set(tops.filter((n, i) => tops.indexOf(n) !== i))];
if (topDupes.length) throw new Error('top-level name collision across modules: ' + topDupes.join(', '));

const out = `/* ${NAME} — generated by build-global.js from the ES modules. Do not edit. */
(function (root) {
  'use strict';
${bodies.join('\n').split('\n').map(l => l ? '  ' + l : l).join('\n')}

  var api = { ${exported.map(n => `${n}: ${n}`).join(', ')} };
  if (typeof module === 'object' && module.exports) module.exports = api;
  root.${NAME} = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;

fs.writeFileSync(path.join(here, OUT), out);
console.log(`${OUT}: ${exported.length} exports, ${(out.length / 1024).toFixed(1)} KB`);
